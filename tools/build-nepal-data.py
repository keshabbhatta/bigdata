"""Builds shared/nepal-data.js: every province, district, local level (with type
and number of wards) of Nepal. Source: github.com/sagautam5/local-states-nepal
(English dataset). The script refuses to write the file unless the totals match
the official structure of Nepal:
    7 provinces, 77 districts, 753 local levels
    (6 metropolitan cities, 11 sub-metropolitan cities, 276 municipalities,
     460 rural municipalities) and 6,743 wards.

Usage:  python tools/build-nepal-data.py            (downloads the dataset)
        python tools/build-nepal-data.py <folder>   (uses provinces.json, districts.json,
                                                     municipalities.json already downloaded)
"""
import json
import os
import sys
import urllib.request
from collections import Counter

BASE = 'https://raw.githubusercontent.com/sagautam5/local-states-nepal/master/dataset/{}/en.json'
OUT = os.path.join(os.path.dirname(__file__), '..', 'shared', 'nepal-data.js')

# Common spellings for a few district names in the dataset.
DISTRICT_FIX = {'Pachthar': 'Panchthar', 'Parwat': 'Parbat', 'Ramechap': 'Ramechhap', 'Acham': 'Achham'}
PROVINCE_FIX = {'Sudurpaschim Province': 'Sudurpashchim Province'}


def load(name, folder):
    if folder:
        with open(os.path.join(folder, f'{name}.json'), encoding='utf-8') as f:
            return json.load(f)
    with urllib.request.urlopen(BASE.format(name), timeout=30) as r:
        return json.loads(r.read().decode('utf-8'))


def main():
    folder = sys.argv[1] if len(sys.argv) > 1 else None
    provinces = load('provinces', folder)
    districts = load('districts', folder)
    locals_ = load('municipalities', folder)

    d_prov = {d['id']: d['province_id'] for d in districts}
    types = Counter(m['category_id'] for m in locals_)
    wards = sum(int(m['wards']) for m in locals_)
    checks = {
        'provinces': (len(provinces), 7), 'districts': (len(districts), 77), 'local levels': (len(locals_), 753),
        'metropolitan cities': (types[1], 6), 'sub-metropolitan cities': (types[2], 11),
        'municipalities': (types[3], 276), 'rural municipalities': (types[4], 460), 'wards': (wards, 6743),
    }
    per_province = {1: (14, 137, 1157), 2: (8, 136, 1271), 3: (13, 119, 1121), 4: (11, 85, 759),
                    5: (12, 109, 983), 6: (10, 79, 718), 7: (9, 88, 734)}
    for pid, (nd, nl, nw) in per_province.items():
        checks[f'province {pid} districts'] = (sum(1 for d in districts if d['province_id'] == pid), nd)
        checks[f'province {pid} local levels'] = (sum(1 for m in locals_ if d_prov[m['district_id']] == pid), nl)
        checks[f'province {pid} wards'] = (sum(int(m['wards']) for m in locals_ if d_prov[m['district_id']] == pid), nw)
    bad = {k: v for k, v in checks.items() if v[0] != v[1]}
    if bad:
        sys.exit(f'Dataset does not match official totals, not writing: {bad}')

    P = [[p['id'], PROVINCE_FIX.get(p['name'], p['name'])] for p in sorted(provinces, key=lambda p: p['id'])]
    D = [[d['id'], d['province_id'], DISTRICT_FIX.get(d['name'], d['name'])] for d in sorted(districts, key=lambda d: d['id'])]
    L = [[m['id'], m['district_id'], m['category_id'], m['name'].strip(), int(m['wards'])]
         for m in sorted(locals_, key=lambda m: m['id'])]

    def rows(a):
        return ',\n'.join('  ' + json.dumps(r, ensure_ascii=False) for r in a)

    js = f"""// GENERATED by tools/build-nepal-data.py. Do not edit by hand.
// Nepal's administrative structure: {len(P)} provinces, {len(D)} districts, {len(L)} local levels, {wards} wards.
// Source: github.com/sagautam5/local-states-nepal (English dataset), checked against the official totals.

/** [id, name] */
export const PROVINCES = [
{rows(P)},
];

/** [id, provinceId, name] */
export const DISTRICTS = [
{rows(D)},
];

/** [id, districtId, type (1 Metropolitan City, 2 Sub-Metropolitan City, 3 Municipality, 4 Rural Municipality), name, number of wards] */
export const LOCAL_LEVELS = [
{rows(L)},
];
"""
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(js)
    print(f'Wrote {os.path.abspath(OUT)}: {len(P)} provinces, {len(D)} districts, {len(L)} local levels, {wards} wards.')


if __name__ == '__main__':
    main()
